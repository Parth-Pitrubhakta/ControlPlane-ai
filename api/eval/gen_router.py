"""Build the router training set.

Responses are generated by the real model so the text features are realistic,
but every defect is planted by us, so the label is known by construction rather
than inferred. That matters: a weak label from our own detector would train the
router to imitate the detector's mistakes.

The grounding defects use the seeded contradiction pairs in corpus/. Each pair
has a governed value and a stale wiki value, so "did the model actually repeat
the stale fact" is an exact string check, not a judgement call.

    python -m api.eval.gen_router --n 500 --out bench/router_train.jsonl
"""

