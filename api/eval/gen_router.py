TENANTS = ["CS-BOT", "KB-COPILOT", "DECIDE"]
GEOS = ["IN", "EU", "US"]


# Response length must vary independently of whether the answer is defective.
# Held fixed, the classifier learns length as a proxy for risk and then rates a
# one-line wrong answer as safe.
LENGTHS = [("in one short sentence", 40), ("in two or three sentences", 110),
           ("in a short paragraph", 170)]


def _sys(fact: dict[str, Any], stale: bool, tenant: str,
         how: str = "in two or three sentences") -> str:
    src = fact["ung"] if stale else fact["gov"]
    who = {"CS-BOT": "a customer support agent",
           "KB-COPILOT": "an internal knowledge assistant",
           "DECIDE": "a regulated decision-support assistant"}[tenant]
    origin = "the internal team wiki" if stale else "the official policy document"
    return (f"You are {who}. Answer {how} using only "
            f"{origin}, which states: {src}. State the value explicitly.")


async def _gen(c: httpx.AsyncClient, sysmsg: str, q: str, maxtok: int = 110) -> str:
    r = await c.post("/chat/completions", json={
        "model": MODEL, "temperature": 0.7, "max_tokens": maxtok,
        "messages": [{"role": "system", "content": sysmsg},
                     {"role": "user", "content": q}]})
    r.raise_for_status()
    return (r.json()["choices"][0]["message"]["content"] or "").strip()


def _build_ctx(fact: dict[str, Any], rng: random.Random, drop: bool) -> list[dict]:
    if drop:
        return []
    ch = [{"id": f"{fact['doc']}#{i}", "text": t, "score": round(rng.uniform(0.62, 0.95), 3)}
          for i, t in enumerate(fact["ctx"])]
    for d in rng.sample(DISTRACT, rng.randint(1, 2)):
        ch.append({"id": f"distract#{abs(hash(d)) % 97}", "text": d,
                   "score": round(rng.uniform(0.20, 0.55), 3)})
    rng.shuffle(ch)
    return ch


async def one(c: httpx.AsyncClient, rng: random.Random, i: int) -> dict[str, Any]:
    fact = rng.choice(FACTS)
    tenant = rng.choices(TENANTS, weights=[5, 3, 2])[0]
    geo = rng.choices(GEOS, weights=[6, 3, 2])[0]
    stale = rng.random() < 0.38          # answer from the stale wiki
    drop_ctx = rng.random() < 0.12       # no retrieval at all
    q = rng.choice(fact["q"])

    how, maxtok = rng.choice(LENGTHS)
    resp = await _gen(c, _sys(fact, stale, tenant, how), q, maxtok)

    defects: list[str] = []
    ambiguous = False
    # A grounding defect only counts if the model actually repeated the stale
    # value. If it stated neither value clearly, we cannot tell by string match,
    # so the row is flagged for adjudication rather than guessed at.
    import re as _re
    if stale and not drop_ctx:
        if _re.search(fact["stale"], resp):
            defects.append("contradicted")
        elif not _re.search(fact["govre"], resp):
            ambiguous = True

    if rng.random() < 0.14:
        lab, sent = rng.choice(PII)
        resp = resp + " " + sent
        defects.append("pii")
    if rng.random() < 0.07:
        resp = resp + " " + rng.choice(UNSAFE)
        defects.append("unsafe")
    if rng.random() < 0.06:
        resp = resp + " " + rng.choice(BIAS)
        defects.append("bias")

    prompt = q
    if rng.random() < 0.06:
        prompt = rng.choice(INJECT) + " " + q
        defects.append("inject")

    tools: list[str] = []
    if tenant == "DECIDE" and rng.random() < 0.5:
        tools = rng.sample(TOOLS_RO, 1)
        if rng.random() < 0.45:
            tools.append(rng.choice(TOOLS_IRREV))
    elif rng.random() < 0.3:
        tools = rng.sample(TOOLS_RO + TOOLS_REV, rng.randint(1, 2))

    return {
        "id": f"r-{uuid.uuid4().hex[:10]}",
        "tenant": tenant, "geo": geo,
        "prompt": prompt, "resp": resp,
        "ctx": _build_ctx(fact, rng, drop_ctx),
        "tools": tools,
        "tok_in": max(1, len(prompt) // 4), "tok_out": max(1, len(resp) // 4),
        "topic": fact["topic"], "from_wiki": stale, "no_ctx": drop_ctx,
        "defects": sorted(set(defects)),
        "ambiguous": ambiguous,
        # y is "does this response hide something material". unverifiable alone
        # is not material: abstaining is cheap and never blocks (invariant 2).
        "y": int(bool(defects)),
        "label_src": "constructed",
    }


async def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=500)
    ap.add_argument("--out", default="bench/router_train.jsonl")
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--conc", type=int, default=12)
    a = ap.parse_args()

    rng = random.Random(a.seed)
    sem = asyncio.Semaphore(a.conc)
    t0 = time.perf_counter()

    async with httpx.AsyncClient(base_url=VLLM, timeout=180) as c:
        async def go(i: int) -> dict[str, Any] | None:
            async with sem:
                for _ in range(3):
                    try:
                        return await one(c, random.Random(a.seed * 100003 + i), i)
                    except Exception:
                        await asyncio.sleep(1.0)
                return None
        rows = [r for r in await asyncio.gather(*(go(i) for i in range(a.n))) if r]

    p = pathlib.Path(a.out)
    p.parent.mkdir(parents=True, exist_ok=True)
    with p.open("w") as fh:
        for r in rows:
            fh.write(json.dumps(r) + "\n")

    pos = sum(r["y"] for r in rows)
    by: dict[str, int] = {}
    for r in rows:
        for d in r["defects"]:
            by[d] = by.get(d, 0) + 1
    print(json.dumps({
        "rows": len(rows), "positives": pos,
        "rate": round(pos / max(1, len(rows)), 3),
        "by_defect": by,
        "by_tenant": {t: sum(1 for r in rows if r["tenant"] == t) for t in TENANTS},
        "secs": round(time.perf_counter() - t0, 1), "out": str(p),
    }, indent=2))


if __name__ == "__main__":
    asyncio.run(main())
